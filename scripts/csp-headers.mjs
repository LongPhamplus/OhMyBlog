#!/usr/bin/env node
/* eslint-disable no-console -- CLI build script, console output is intended */
// Post-build: scan dist/**/*.html, hash every inline <script>, and write
// dist/_headers (Cloudflare Pages format) with a strict CSP + security headers.
// Run AFTER `astro build` and `pagefind`. Fails the build if something is off.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from "node:fs";
import { join } from "node:path";

// ---------------------------------------------------------------- config ---
const DIST = process.argv[2] ?? "dist";
const FEATURES = {
  giscus: true, //              comments (giscus.app iframe + client.js)
  cloudflareAnalytics: true, // Cloudflare Web Analytics beacon (cookieless)
};
// ----------------------------------------------------------------------------

function* walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) yield* walk(p);
    else if (p.endsWith(".html")) yield p;
  }
}

if (!existsSync(DIST)) {
  console.error(`[csp] ${DIST}/ not found - run the build first`);
  process.exit(1);
}

const SCRIPT_RE = /<script\b([^>]*)>([\s\S]*?)<\/script>/gi;
const NON_JS_TYPE = /\btype\s*=\s*["']?(application\/(ld\+)?json|text\/plain)["']?/i;
const hashes = new Set();
let pages = 0;

for (const file of walk(DIST)) {
  pages++;
  const html = readFileSync(file, "utf8");
  for (const [, attrs, body] of html.matchAll(SCRIPT_RE)) {
    if (/\bsrc\s*=/i.test(attrs)) continue; //    external -> covered by host list
    if (NON_JS_TYPE.test(attrs)) continue; //     data block, never executed
    if (body.length === 0) continue;
    const h = createHash("sha256").update(body, "utf8").digest("base64");
    hashes.add(`'sha256-${h}'`);
  }
}

if (pages === 0) {
  console.error("[csp] no HTML files found in dist/");
  process.exit(1);
}

const scriptSrc = ["'self'", "'wasm-unsafe-eval'", ...[...hashes].sort()]; // wasm: Pagefind
const connectSrc = ["'self'"];
const frameSrc = [];
const styleSrc = ["'self'", "'unsafe-inline'"];
if (FEATURES.giscus) {
  // client.js loads the iframe and injects https://giscus.app/default.css into the host page
  scriptSrc.push("https://giscus.app");
  frameSrc.push("https://giscus.app");
  styleSrc.push("https://giscus.app");
}
if (FEATURES.cloudflareAnalytics) {
  scriptSrc.push("https://static.cloudflareinsights.com");
  connectSrc.push("https://cloudflareinsights.com");
}

const csp = [
  "default-src 'self'",
  `script-src ${scriptSrc.join(" ")}`,
  // Shiki + view transitions + medium-zoom + Mermaid write inline style attributes.
  // Style injection on a static site without user input is a low risk; script stays strict.
  `style-src ${styleSrc.join(" ")}`,
  "img-src 'self' data:",
  "font-src 'self'",
  `connect-src ${connectSrc.join(" ")}`,
  `frame-src ${frameSrc.length ? frameSrc.join(" ") : "'none'"}`,
  "frame-ancestors 'none'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "upgrade-insecure-requests",
].join("; ");

const headers = `# Generated by scripts/csp-headers.mjs - do not edit by hand.
/*
  Content-Security-Policy: ${csp}
  Strict-Transport-Security: max-age=63072000; includeSubDomains; preload
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=(), serial=(), bluetooth=(), browsing-topics=()
  Cross-Origin-Opener-Policy: same-origin
  Cross-Origin-Resource-Policy: same-origin

/_astro/*
  Cache-Control: public, max-age=31536000, immutable

/pagefind/*
  Cache-Control: public, max-age=3600
`;

// Cloudflare Pages: each header line must stay under 2,000 chars.
const longest = Math.max(...headers.split("\n").map(l => l.length));
if (longest > 2000) {
  console.error(`[csp] a header line is ${longest} chars (>2000). Too many inline scripts - move some to bundled <script> tags.`);
  process.exit(1);
}

if (existsSync(join(DIST, "_headers"))) {
  console.warn("[csp] overwriting dist/_headers (remove public/_headers, this script owns it)");
}
writeFileSync(join(DIST, "_headers"), headers);
console.log(`[csp] ${pages} pages, ${hashes.size} inline script hash(es) -> ${DIST}/_headers`);
